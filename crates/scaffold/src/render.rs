//! Renderer: compose small reusable string fragments into a standalone,
//! compilable application project.
//!
//! No `templates/<preset>/` copies of whole apps exist here. Every preset is
//! produced by the same fragment functions driven by the declarative
//! [`ResolvedSpec`](super::spec::ResolvedSpec): layout selects panel slots,
//! features select code sections. Same input always yields the same bytes
//! (no timestamps, fixed file order).

use super::model::Feature;
use super::spec::{ResolvedSpec, ScaffoldError};
use std::collections::BTreeSet;
use std::path::Path;

/// A generated file: project-relative path plus exact bytes.
pub struct GeneratedFile {
    pub path: &'static str,
    pub contents: String,
}

/// Render every project file in fixed order. Pure and deterministic.
pub fn render_project(spec: &ResolvedSpec) -> Vec<GeneratedFile> {
    vec![
        GeneratedFile {
            path: "Cargo.toml",
            contents: cargo_toml(spec),
        },
        GeneratedFile {
            path: "src/main.rs",
            contents: main_rs(spec),
        },
        GeneratedFile {
            path: "src/app.rs",
            contents: app_rs(spec),
        },
        GeneratedFile {
            path: "src/demo.rs",
            contents: demo_rs(spec),
        },
        GeneratedFile {
            path: ".scaffold.toml",
            contents: scaffold_toml(spec),
        },
        GeneratedFile {
            path: "AGENTS.md",
            contents: agents_md(spec),
        },
        GeneratedFile {
            path: "README.md",
            contents: readme_md(spec),
        },
    ]
}

/// Write the rendered project under `out_dir`, creating directories.
/// Fails before writing anything when `out_dir` already exists and is
/// non-empty, so generation never merges into an unrelated tree.
pub fn write_project(spec: &ResolvedSpec, out_dir: &Path) -> Result<(), ScaffoldError> {
    if out_dir.exists() {
        let non_empty = std::fs::read_dir(out_dir)
            .map_err(|err| {
                ScaffoldError(format!(
                    "cannot inspect output directory '{}': {err}",
                    out_dir.display()
                ))
            })?
            .next()
            .is_some();
        if non_empty {
            return Err(ScaffoldError(format!(
                "output directory '{}' already exists and is not empty. \
                 Remove it or pass --output-dir <empty-dir>.",
                out_dir.display()
            )));
        }
    }
    for file in render_project(spec) {
        let target = out_dir.join(file.path);
        if let Some(parent) = target.parent() {
            std::fs::create_dir_all(parent).map_err(|err| {
                ScaffoldError(format!(
                    "cannot create directory '{}': {err}",
                    parent.display()
                ))
            })?;
        }
        std::fs::write(&target, file.contents).map_err(|err| {
            ScaffoldError(format!("cannot write file '{}': {err}", target.display()))
        })?;
    }
    Ok(())
}

const SHELL_GIT_URL: &str = "https://github.com/JhonMA82/iced-desktop-shell";

fn has(spec: &ResolvedSpec, feature: Feature) -> bool {
    spec.has_feature(feature)
}

