fn main_rs(spec: &ResolvedSpec) -> String {
    format!(
        "//! {title} — technical desktop application entry point.\n\
         //!\n\
         //! Generated by the iced-desktop-shell scaffolder (layout: {layout}).\n\
         //! Normal, editable application code.\n\
         \n\
         mod app;\n\
         mod demo;\n\
         \n\
         use app::{{AppState, Message, update, view}};\n\
         use iced::event;\n\
         \n\
         fn main() -> iced::Result {{\n\
         \x20   iced::application(AppState::new, update, view)\n\
         \x20       .title(\"{title}\")\n\
         \x20       .theme(|state: &AppState| state.shell.theme.to_iced_theme())\n\
         \x20       .subscription(|_state: &AppState| {{\n\
         \x20           event::listen_with(|event, status, _window| Some(Message::Event(event, status)))\n\
         \x20       }})\n\
         \x20       .window(iced::window::Settings {{\n\
         \x20           size: iced::Size::new(1280.0, 800.0),\n\
         \x20           min_size: Some(iced::Size::new(800.0, 600.0)),\n\
         \x20           position: iced::window::Position::Centered,\n\
         \x20           ..Default::default()\n\
         \x20       }})\n\
         \x20       .run()\n\
         }}\n",
        title = spec.app_title,
        layout = spec.layout.kebab(),
    )
}

