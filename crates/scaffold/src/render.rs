fn shell_dependency(spec: &ResolvedSpec) -> String {
    match spec.shell_path.as_ref() {
        Some(path) => {
            format!("desktop-shell = {{ package = \"desktop-shell\", path = \"{path}\" }}")
        }
        None => {
            format!("desktop-shell = {{ package = \"desktop-shell\", git = \"{SHELL_GIT_URL}\" }}")
        }
    }
}

fn cargo_toml(spec: &ResolvedSpec) -> String {
    format!(
        "[package]\nname = \"{crate_name}\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\
         \n[workspace]\n\
         \n[dependencies]\n{shell_dep}\niced = \"0.14\"\n",
        crate_name = spec.crate_name,
        shell_dep = shell_dependency(spec),
    )
}

