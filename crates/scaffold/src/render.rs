fn demo_widget_imports(spec: &ResolvedSpec) -> String {
    let mut names = BTreeSet::new();
    names.insert("column");
    names.insert("container");
    names.insert("text");
    if has(spec, Feature::Explorer) || has(spec, Feature::BottomPanel) {
        names.insert("button");
    }
    if has(spec, Feature::Inspector) {
        // right panel content is read-only text; nothing extra.
    }
    if has(spec, Feature::Explorer)
        || has(spec, Feature::Inspector)
        || has(spec, Feature::BottomPanel)
    {
        names.insert("scrollable");
    }
    if has(spec, Feature::Explorer) || has(spec, Feature::BottomPanel) {
        names.insert("Column");
    }
    if has(spec, Feature::BottomPanel) {
        names.insert("Space");
        names.insert("row");
    }
    let list: Vec<&str> = names.into_iter().collect();
    format!("use iced::widget::{{{}}};\n", list.join(", "))
}

